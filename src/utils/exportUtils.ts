import { Meeting, ActionItem, CrossMeetingTrends } from '../types/meeting';

// Download file helper
function downloadFile(content: string, filename: string, type: string) {
  const blob = new Blob([content], { type });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// 1. Export Action Plan to CSV
export function exportActionPlanToCSV(actionPlan: ActionItem[], filenamePrefix = 'Action_Plan'): void {
  const headers = [
    'Task',
    'Assignee',
    'Role',
    'Responsibilities',
    'Timeline',
    'Deadline Date',
    'Priority',
    'Status',
    'Deliverable',
    'Dependencies',
    'Meeting Title'
  ];

  const escapeCSV = (val?: string) => {
    if (!val) return '""';
    const clean = val.replace(/"/g, '""');
    return `"${clean}"`;
  };

  const rows = actionPlan.map(item => [
    escapeCSV(item.task),
    escapeCSV(item.assignee),
    escapeCSV(item.role),
    escapeCSV(item.responsibilities),
    escapeCSV(item.timeline),
    escapeCSV(item.deadlineDate),
    escapeCSV(item.priority.toUpperCase()),
    escapeCSV(item.status.toUpperCase()),
    escapeCSV(item.deliverable || 'N/A'),
    escapeCSV(item.dependencies || 'None'),
    escapeCSV(item.meetingTitle)
  ]);

  const csvContent = [headers.join(','), ...rows.map(r => r.join(','))].join('\n');
  const dateStr = new Date().toISOString().split('T')[0];
  downloadFile(csvContent, `${filenamePrefix}_${dateStr}.csv`, 'text/csv;charset=utf-8;');
}

// 2. Export Meeting Summary & Action Plan to Markdown
export function exportMeetingToMarkdown(meeting: Meeting): void {
  const md = `# ${meeting.title}
**Date:** ${meeting.date} | **Duration:** ${meeting.duration} | **Department:** ${meeting.department}
**Attendees:** ${meeting.attendees.join(', ')}

---

## 🎯 Executive Summary
${meeting.summary.tldr}

### Key Decisions Made
${meeting.summary.keyDecisions.map(d => `- **${d}**`).join('\n')}

### Critical Highlights
${meeting.summary.criticalHighlights.map(h => `- ${h}`).join('\n')}

### Risks & Blockers
${meeting.summary.risksAndBlockers.map(r => `- ⚠️ ${r}`).join('\n')}

---

## 👥 Team Roles & Responsibilities Matrix
| Team Member | Professional Role | Primary Responsibility | Key Deliverables |
| :--- | :--- | :--- | :--- |
${meeting.teamResponsibilities.map(r => `| **${r.member}** | ${r.role} | ${r.primaryResponsibility} | ${r.deliverables.join('; ')} |`).join('\n')}

---

## 📋 Action Plan & Timelines
| Status | Priority | Task | Assignee | Role | Timeline / Deadline | Deliverable | Dependencies |
| :---: | :---: | :--- | :--- | :--- | :--- | :--- | :--- |
${meeting.actionPlan.map(item => `| \`[${item.status.toUpperCase()}]\` | **${item.priority.toUpperCase()}** | ${item.task} | **${item.assignee}** | ${item.role} | ${item.timeline} | ${item.deliverable || 'N/A'} | ${item.dependencies || 'None'} |`).join('\n')}

---

## 🏷️ Key Topics Discussed
${meeting.topics.map(t => `- **${t.name}** (${t.category}, Weight: ${t.weight}/10, Sentiment: ${t.sentiment})\n  ${t.keyPoints.map(kp => `  * ${kp}`).join('\n')}`).join('\n')}

---
*Generated by SyncPulse Meeting Intelligence Hub on ${new Date().toLocaleDateString()}*
`;

  const dateStr = meeting.date || new Date().toISOString().split('T')[0];
  const safeTitle = meeting.title.replace(/[^a-zA-Z0-9_-]/g, '_');
  downloadFile(md, `${safeTitle}_Summary_${dateStr}.md`, 'text/markdown;charset=utf-8;');
}

// 3. Export Comprehensive Multi-Meeting Trend Report
export function exportTrendsToMarkdown(trends: CrossMeetingTrends, meetings: Meeting[]): void {
  const md = `# Cross-Meeting Intelligence & Trend Analysis Report
**Generated:** ${new Date().toLocaleDateString()}
**Meetings Analyzed:** ${meetings.length} meetings (${meetings[0]?.date || 'Past'} to ${meetings[meetings.length - 1]?.date || 'Present'})

---

## 📊 Executive Strategic Takeaways
${trends.executiveTakeaways.map(t => `- 💡 **${t}**`).join('\n')}

---

## ⚠️ Systemic & Recurring Blockers
${trends.recurringBlockers.map(b => `- 🚨 ${b}`).join('\n')}

---

## 📈 Common Topics & Trend Trajectory
| Topic Name | Category | Total Mentions | Trend | Avg Intensity | Summary & Evolution Insight |
| :--- | :--- | :---: | :---: | :---: | :--- |
${trends.commonTopics.map(t => `| **${t.topic}** | ${t.category} | ${t.totalMentions} | **${t.trend.toUpperCase()}** | ${t.averageIntensity}/10 | ${t.summaryInsight} |`).join('\n')}

---

## 🗓️ Meeting Chronology
${meetings.map(m => `### ${m.title} (${m.date}) - ${m.department}
- **Sentiment:** ${m.summary.sentiment.toUpperCase()}
- **TL;DR:** ${m.summary.tldr}
- **Key Action Items:** ${m.actionPlan.length} tasks (${m.actionPlan.filter(a => a.status === 'completed').length} completed)
`).join('\n')}

---
*Exported from SyncPulse Intelligence Dashboard*
`;

  downloadFile(md, `Cross_Meeting_Trends_Report_${new Date().toISOString().split('T')[0]}.md`, 'text/markdown;charset=utf-8;');
}

// 4. Export JSON
export function exportAllDataToJSON(meetings: Meeting[], trends: CrossMeetingTrends): void {
  const data = {
    exportedAt: new Date().toISOString(),
    version: '1.0',
    meetings,
    trends
  };
  downloadFile(JSON.stringify(data, null, 2), `SyncPulse_Workspace_Backup_${new Date().toISOString().split('T')[0]}.json`, 'application/json');
}
